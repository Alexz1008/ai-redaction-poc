logger = logging.getLogger(__name__)
REVIEW_MESSAGE = (
    "Generated by Azure Foundry. Structural PDF checks passed; redaction accuracy and "
    "layout have not been independently verified. Review the PDF before sharing."
)


@dataclass(frozen=True)
class FoundrySettings:
    storage: Settings
    project_endpoint: str
    agent_name: str
    execution_mode: Literal["native", "toolbox"] = "native"

    @classmethod
    def from_env(cls) -> "FoundrySettings":
        try:
            endpoint = validate_project_endpoint(
                os.environ.get("AZURE_FOUNDRY_PROJECT_ENDPOINT", ""),
            )
        except PocError:
            logger.error("Missing or invalid Foundry project endpoint.")
            raise HTTPException(503, "Backend Foundry settings are not configured correctly.") from None
        mode = os.environ.get("AZURE_FOUNDRY_EXECUTION_MODE", "native").strip().lower()
        agent = os.environ.get("AZURE_FOUNDRY_AGENT_NAME", "sac-redaction").strip()
        if (
            not re.fullmatch(r"[a-zA-Z0-9_-]+", agent)
            or mode not in ("native", "toolbox")
        ):
            logger.error("Missing or invalid Foundry project endpoint or agent name.")
            raise HTTPException(503, "Backend Foundry settings are not configured correctly.")
        return cls(
            Settings.from_env(require_language=False), endpoint, agent,
            "native" if mode == "native" else "toolbox",
        )


class Resources(BaseModel):
    containers: set[str] = Field(default_factory=set)
    response_ids: set[str] = Field(default_factory=set)
    file_ids: set[str] = Field(default_factory=set)
    agent: str | None = None
    toolbox: str | None = None


class FoundryRecord(Record):
    execution_mode: Literal["native", "toolbox"] = "toolbox"
    agent_name: str | None = None
    processing_started: bool = False
    resources: Resources = Field(default_factory=Resources)
    generation_report: dict | None = None


class FoundryRedactionService(RedactionService):
    def __init__(
        self, settings: FoundrySettings, storage: BlobServiceClient,
        http: httpx.Client, credential: DefaultAzureCredential,
        background_tasks: BackgroundTasks,
    ):
        super().__init__(settings.storage, storage, http)
        self.foundry = settings
        self.credential = credential
        self.background_tasks = background_tasks

    def _load(self, user: User, document_id: UUID) -> FoundryRecord:
        try:
            data = self._record_blob(user, document_id).download_blob().readall()
        except ResourceNotFoundError:
            raise HTTPException(404, "Document not found.") from None
        try:
            record = FoundryRecord.model_validate_json(data)
        except ValidationError:
            raise RedactionError("Stored Foundry job record is invalid.") from None
        if record.id != document_id:
            raise RedactionError("Stored job identity is invalid.")
        if record.provider != "foundry":
            raise HTTPException(409, "This document requires the Azure Language redaction backend.")
        return record

    def submit(self, user: User, pdf: bytes) -> Job:
        reader = self._reader(pdf, uploaded=True)
        record = FoundryRecord(
            id=uuid4(), provider="foundry", page_count=len(reader.pages),
            execution_mode=self.foundry.execution_mode, agent_name=self.foundry.agent_name,
            message="Queued for Azure Foundry processing.",
        )
        self.storage.get_blob_client(
            self.settings.originals_container,
            f"{user.storage_prefix}/{record.id}/document.pdf",
        ).upload_blob(
            pdf, overwrite=False, content_settings=ContentSettings(content_type="application/pdf"),
        )
        self._save(user, record)
        self._schedule(user, record)
        return self._job(record)

    def status(self, user: User, document_id: UUID) -> Job:
        record = self._load(user, document_id)
        self._schedule(user, record)
        return self._job(record)

    def _schedule(self, user: User, record: FoundryRecord) -> None:
        if record.status == "running" or record.cleanup_pending:
            self.background_tasks.add_task(process_foundry_job, user, record.id)

    @staticmethod
    def _job(record: Record) -> Job:
        return Job(
            id=record.id, status=record.status, message=record.message,
            warning_count=record.warning_count,
        )

    def process(self, user: User, document_id: UUID) -> None:
        blob = self._record_blob(user, document_id)
        try:
            lease = blob.acquire_lease(lease_duration=60)
        except HttpResponseError as error:
            if getattr(error, "error_code", None) == "LeaseAlreadyPresent":
                return
            raise
        try:
            record = self._load(user, document_id)
            if record.status != "running" and not record.cleanup_pending:
                return
            # Keep the persisted job locked while the model executes, not the HTTP upload.
            with ThreadPoolExecutor(max_workers=1) as executor:
                future = executor.submit(self._process_locked, user, record, lease)
                while not wait([future], timeout=20).done:
                    lease.renew()
                future.result()
        finally:
            try:
                lease.release()
            except AzureError as error:
                logger.error("Foundry job lease release failed (%s).", type(error).__name__)

    def _process_locked(
        self, user: User, record: FoundryRecord, lease: BlobLeaseClient,
    ) -> None:
        with TemporaryDirectory(prefix="redaction-foundry-") as directory:
            root = Path(directory)
            runner = NativeFoundry if record.execution_mode == "native" else FoundryPoc
            poc = runner(
                self.http, self.credential, self.foundry.project_endpoint, root,
            )
            poc.containers = set(record.resources.containers)
            poc.response_ids = set(record.resources.response_ids)
            poc.file_ids = set(record.resources.file_ids)
            poc.agent = record.resources.agent
            poc.toolbox = record.resources.toolbox

            def checkpoint() -> None:
                record.resources = Resources(
                    containers=poc.containers, response_ids=poc.response_ids,
                    file_ids=poc.file_ids,
                    agent=poc.agent, toolbox=poc.toolbox,
                )
                self._save(user, record, lease)

            poc.on_resources_changed = checkpoint
            try:
                if record.status == "running":
                    if record.processing_started:
                        record.status = "failed"
                        record.message = (
                            "Foundry processing was interrupted. Temporary resources are being "
                            "cleaned up. Upload the original again to retry."
                        )
                    else:
                        record.processing_started = True
                        record.cleanup_pending = True
                        record.message = "Azure Foundry is processing the original PDF."
                        checkpoint()
                        self._generate(user, record, poc, root)
            except (PocError, RedactionError, AzureError, httpx.HTTPError,
                    PyPdfError, OSError, ValueError, KeyError) as error:
                logger.error("Foundry document processing failed (%s).", type(error).__name__)
                record.status = "failed"
                record.redacted_blob = None
                record.message = (
                    "Foundry could not complete PDF generation and structural checks. "
                    "Retry the original or contact the administrator."
                )
            finally:
                errors = poc.cleanup()
                record.cleanup_pending = bool(errors)
                record.warning_count = (1 if record.status == "succeeded" else 0) + bool(errors)
                if errors:
                    logger.error("Foundry temporary resource cleanup failed for %s operation(s).",
                                 len(errors))
                    record.message = (
                        (REVIEW_MESSAGE if record.status == "succeeded" else record.message or "")
                        + " Temporary Azure resource cleanup is pending; contact the administrator."
                    )
                elif record.status == "succeeded":
                    record.message = REVIEW_MESSAGE
                checkpoint()

    def _generate(
        self, user: User, record: FoundryRecord, poc: FoundryPoc, root: Path,
    ) -> None:
        prefix = f"{user.storage_prefix}/{record.id}"
        original = self.storage.get_blob_client(
            self.settings.originals_container, f"{prefix}/document.pdf",
        ).download_blob().readall()
        source = root / "document.pdf"
        source.write_bytes(original)
        report = poc.run(source, record.agent_name or self.foundry.agent_name)
        for item in report["generated"]:
            name = item["file"]
            is_pdf = name == "document_Redacted.pdf"
            destination = f"{prefix}/redacted.pdf" if is_pdf else f"{prefix}/previews/{name}"
            self.storage.get_blob_client(
                self.settings.redacted_container, destination,
            ).upload_blob(
                (root / name).read_bytes(), overwrite=True,
                content_settings=ContentSettings(
                    content_type="application/pdf" if is_pdf else "image/png",
                ),
            )
        record.generation_report = report
        record.redacted_blob = f"{prefix}/redacted.pdf"
        record.status = "succeeded"


def get_foundry_service(
    background_tasks: BackgroundTasks,
) -> Generator[FoundryRedactionService, None, None]:
    settings = FoundrySettings.from_env()
    with (
        DefaultAzureCredential() as credential,
        BlobServiceClient(
            settings.storage.storage_url,
            credential=settings.storage.account_key or credential,
            logging_enable=False,
        ) as storage,
        httpx.Client(timeout=httpx.Timeout(1800, connect=30), follow_redirects=False) as http,
    ):
        yield FoundryRedactionService(settings, storage, http, credential, background_tasks)


def process_foundry_job(user: User, document_id: UUID) -> None:
    try:
        # Background work owns its clients; request-scoped dependencies may already be closed.
        with contextmanager(get_foundry_service)(BackgroundTasks()) as service:
            service.process(user, document_id)
    except (AzureError, httpx.HTTPError, RedactionError, HTTPException) as error:
        logger.error("Foundry background job failed (%s); status polling can retry cleanup.",
                     type(error).__name__)
